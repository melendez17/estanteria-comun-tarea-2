async function contar(pagina, selector, cantidad) {
  await pagina.waitForFunction(([sel,n]) => document.querySelectorAll(sel).length === n, [selector,cantidad]);
}
async function medir(browser, etiqueta) {
  const contexto = await browser.newContext({ viewport:{width:1440,height:1000} });
  const pagina = await contexto.newPage();
  const cdp = await contexto.newCDPSession(pagina);
  await cdp.send('Network.enable');
  const cargas = [];
  cdp.on('Network.loadingFinished', evento => cargas.push(evento.encodedDataLength));
  await pagina.goto('http://127.0.0.1:4173/');
  await pagina.waitForLoadState('networkidle');
  const recursos = await pagina.evaluate(() => performance.getEntriesByType('resource').map(r=>({ url:r.name,bytes:r.transferSize,decoded:r.decodedBodySize })));
  const medicion = { etiqueta, peticiones:cargas.length, bytesTransferidos:cargas.reduce((a,b)=>a+b,0), recursos };
  fs.writeFileSync(path.join(capturas,`red-${etiqueta}.json`),JSON.stringify(medicion,null,2));
  await pagina.screenshot({path:path.join(capturas,`buscador-${etiqueta}.png`),fullPage:true});
  await contexto.close();
  return medicion;
}
